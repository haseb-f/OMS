import { Type } from 'class-transformer';
import {
  IsDateString,
  IsEnum,
  IsIn,
  IsInt,
  IsOptional,
  IsString,
  Max,
  Min,
} from 'class-validator';
import { InvestmentOpportunityStatus } from '@prisma/client';
import { TransformEnumList } from '../../common/query/enum-list';

export class FindInvestmentOpportunitiesQueryDto {
  @TransformEnumList()
  @IsEnum(InvestmentOpportunityStatus, { each: true })
  @IsOptional()
  status?: InvestmentOpportunityStatus[];

  /** Matches against code or name (Arabic/English). */
  @IsString()
  @IsOptional()
  search?: string;

  @IsDateString()
  @IsOptional()
  dateFrom?: string;

  @IsDateString()
  @IsOptional()
  dateTo?: string;

  @Type(() => Number)
  @IsInt()
  @Min(1)
  @IsOptional()
  page?: number = 1;

  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(200)
  @IsOptional()
  pageSize?: number = 20;

  @IsString()
  @IsOptional()
  sortBy?: string;

  @IsIn(['asc', 'desc'])
  @IsOptional()
  sortOrder?: 'asc' | 'desc' = 'desc';
}
